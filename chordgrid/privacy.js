const privacyLanguageSelect = document.getElementById("privacy-language");
const privacyMetaDescription = document.querySelector('meta[name="description"]');
const privacyThemeToggle = document.querySelector(".theme-toggle");
const privacyLanguageStorageKey = "chordgrid-privacy-language";

function normalizePrivacyLocale(locale) {
  if (!locale) return null;

  const normalized = locale.replace("_", "-").toLowerCase();

  if (normalized.startsWith("zh")) return "zh-Hans";

  const baseLocale = normalized.split("-")[0];
  return Object.hasOwn(privacyTranslations, baseLocale) ? baseLocale : null;
}

function storedPrivacyLocale() {
  try {
    return normalizePrivacyLocale(localStorage.getItem(privacyLanguageStorageKey));
  } catch (error) {
    return null;
  }
}

function browserPrivacyLocale() {
  const browserLocales = navigator.languages?.length ? navigator.languages : [navigator.language];

  for (const locale of browserLocales) {
    const supportedLocale = normalizePrivacyLocale(locale);
    if (supportedLocale) return supportedLocale;
  }

  return "en";
}

function updatePrivacyThemeLabel(translation) {
  if (!privacyThemeToggle) return;

  const isDark = document.documentElement.dataset.theme === "dark";
  const label = isDark ? translation.switchToLight : translation.switchToDark;
  privacyThemeToggle.setAttribute("aria-label", label);
  privacyThemeToggle.title = label;
}

function applyPrivacyLocale(locale, updateUrl = false) {
  const supportedLocale = normalizePrivacyLocale(locale) || "en";
  const translation = privacyTranslations[supportedLocale];

  document.documentElement.lang = supportedLocale;
  document.title = `ChordGrid — ${translation.title}`;

  if (privacyMetaDescription) privacyMetaDescription.content = translation.metaDescription;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (translation[key]) element.textContent = translation[key];
  });

  if (privacyLanguageSelect) {
    privacyLanguageSelect.value = supportedLocale;
    privacyLanguageSelect.setAttribute("aria-label", translation.language);
  }

  updatePrivacyThemeLabel(translation);

  if (updateUrl) {
    const url = new URL(window.location.href);
    url.searchParams.set("lang", supportedLocale);
    history.replaceState(null, "", url);
  }

  return supportedLocale;
}

const privacyUrlLocale = normalizePrivacyLocale(new URLSearchParams(window.location.search).get("lang"));
const initialPrivacyLocale = privacyUrlLocale || storedPrivacyLocale() || browserPrivacyLocale();
let activePrivacyLocale = applyPrivacyLocale(initialPrivacyLocale);

privacyLanguageSelect?.addEventListener("change", () => {
  activePrivacyLocale = applyPrivacyLocale(privacyLanguageSelect.value, true);

  try {
    localStorage.setItem(privacyLanguageStorageKey, activePrivacyLocale);
  } catch (error) {
    // The selected language still applies when storage is unavailable.
  }
});

privacyThemeToggle?.addEventListener("click", () => {
  updatePrivacyThemeLabel(privacyTranslations[activePrivacyLocale]);
});
